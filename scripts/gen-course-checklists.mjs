// Builds constants/courseChecklists.ts from the researched checklist JSON
// (~/Desktop/Seatime Tracker/2.4.0 Additions/*_course_checklists.json and the
// NEW CODES lists in the matching *_notes.md). Re-run after updating research.
//   node scripts/gen-course-checklists.mjs <dir>
import fs from 'fs';
import path from 'path';

const dir = process.argv[2];
const files = fs.readdirSync(dir).filter((f) => /_course_checklists\.json$/.test(f) || f === 'samsa_pathways.json');

const sourceName = (src) => {
  const file = src.split('#')[0].split('/').pop().replace(/\.md$/, '');
  const m = file.match(/^(msn|mgn|min|msf)-(\d+)/i);
  if (m) return `${m[1].toUpperCase()} ${m[2]}`;
  return src.startsWith('http') ? new URL(src).hostname.replace(/^www\./, '') : file.replace(/-/g, ' ');
};

const checklists = {};
const newCodes = {};
for (const f of files) {
  const data = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const entries = Array.isArray(data)
    ? data.filter((p) => p.courses || p.checklist).map((p) => [p.id, p.checklist ?? { exam: p.exam ?? 'oral', items: p.courses.map((c) => ({ type: 'course', ...c })) }])
    : Object.entries(data);
  for (const [id, list] of entries) {
    const items = list.items.map((i) => ({
      code: i.code,
      label: i.label,
      type: i.type ?? 'course',
      validity: i.validity ?? 'none',
      ...(i.alternatives?.length ? { alternatives: i.alternatives } : {}),
      ...(i.note ? { note: i.note } : {}),
      ...(i.optional ? { optional: true } : {}),
    }));
    const sources = Array.from(new Set(list.items.map((i) => i.source).filter(Boolean).map(sourceName)));
    checklists[id] = { exam: list.exam, ...(list.exam_note ? { examNote: list.exam_note } : {}), items, sources };
  }
  const notes = path.join(dir, f.replace(/\.json$/, '_notes.md').replace('samsa_pathways_notes', 'SAMSA_Pathway_Spec'));
  if (fs.existsSync(notes)) {
    const md = fs.readFileSync(notes, 'utf8');
    const block = md.split(/NEW CODES[^\n]*\n/)[1]?.split(/\n## /)[0] ?? '';
    for (const m of block.matchAll(/^- `([a-z0-9_]+)`:? (.+)$/gm)) newCodes[m[1]] = m[2].trim();
  }
}

// Codes the provider research added to COURSE_CODES.md ("code   label" lines).
const codeFiles = [path.join(dir, 'COURSE_CODES.md'), ...fs.readdirSync(path.join(dir, 'providers')).filter((f) => f.endsWith('NEW_CODES.txt')).map((f) => path.join(dir, 'providers', f))];
for (const codesMd of codeFiles) {
  for (const m of fs.readFileSync(codesMd, 'utf8').matchAll(/^([a-z0-9_]+)\s{2,}(\S.*)$/gm)) {
    if (!newCodes[m[1]]) newCodes[m[1]] = m[2].trim();
  }
}

