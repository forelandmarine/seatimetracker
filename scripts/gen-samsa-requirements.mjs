// Builds constants/samsaRequirements.ts from the SAMSA research
// (samsa_pathways.json, Merchant Shipping (Training, Certification and Safe
// Manning) Regulations 2021). Re-run after updating the research.
//   node scripts/gen-samsa-requirements.mjs "<.../2.4.0 Additions>"
import fs from 'fs';
import path from 'path';

const data = JSON.parse(fs.readFileSync(path.join(process.argv[2], 'samsa_pathways.json'), 'utf8'));
const toReq = (p) => ({
  id: p.id,
  title: p.title,
  regulation: p.regulation,
  description: p.description,
  category: p.category,
  ...(p.seaServiceDays ? { totalDays: p.seaServiceDays } : {}),
  ...(p.watchkeepingDays ? { watchkeepingDays: p.watchkeepingDays } : {}),
  ...(p.seaServiceHours ? { totalHours: p.seaServiceHours } : {}),
  requirements: p.requirements,
  notes: p.notes ?? [],
});
const deck = data.filter((p) => p.department === 'deck').map(toReq);
const eng = data.filter((p) => p.department === 'engineering').map(toReq);
const ts = `// GENERATED by scripts/gen-samsa-requirements.mjs from the 2.4.0 SAMSA research.
// Source: Merchant Shipping (Training, Certification and Safe Manning)
// Regulations 2021 (GN 219 of 2021), SAMSA Marine Notices and application forms.
// SAMSA issues no yacht certificate: yacht skippers fall under the small vessel
// regime, and yacht service towards officer CoCs is credited for a CoC endorsed
// Non-Trading (Marine Notice 20 of 2016). Do not edit by hand.
import type { MCARequirement } from './mcaRequirements';

export const SAMSA_DECK_REQUIREMENTS: MCARequirement[] = ${JSON.stringify(deck, null, 2)};

export const SAMSA_ENGINEERING_REQUIREMENTS: MCARequirement[] = ${JSON.stringify(eng, null, 2)};
`;
fs.writeFileSync(new URL('../constants/samsaRequirements.ts', import.meta.url), ts);
console.log('deck', deck.length, 'engineering', eng.length);
