// Verifies candidate course-date sources and writes src/data/course-date-sources.ts.
//   npx tsx scripts/probe-course-dates.ts <candidates.json> [--dry]
// Candidates are either directory rows ({ id, datesUrl }, read as JSON-LD, as in
// 2.4.0) or full sources ({ provider_id, dates_url, parser, config }) found by
// the 2.5.0 discovery passes. Each distinct URL is fetched once, one request at a
// time, 2 s apart, with the same user agent as the weekly refresh. A source is
// kept only if it returns at least one upcoming date mapped to a course code.
import fs from 'fs';
import { readSource, type DateSource } from '../src/services/courseDates.js';

type Candidate = DateSource | { id: string; datesUrl: string | null };
const input = JSON.parse(fs.readFileSync(process.argv[2], 'utf8')) as Candidate[];
const dry = process.argv.includes('--dry');

const sources: DateSource[] = [];
for (const c of input) {
  if ('provider_id' in c) sources.push(c);
  else if (c.datesUrl) sources.push({ provider_id: c.id, dates_url: c.datesUrl, parser: 'jsonld' });
}

const results = new Map<string, number>();
const out: (DateSource & { found: number })[] = [];
let n = 0;
for (const src of sources) {
  const key = `${src.parser}|${src.dates_url}|${JSON.stringify(src.config ?? null)}`;
  if (!results.has(key)) {
    try {
      results.set(key, (await readSource(src)).length);
    } catch (err: any) {
      results.set(key, 0);
      console.log('failed', src.dates_url, err?.message ?? err);
    }
    await new Promise((r) => setTimeout(r, 2000));
  }
  const found = results.get(key)!;
  if (found > 0) out.push({ ...src, found });
  if (++n % 25 === 0) console.log('probed', n, 'with dates', out.length);
}

const byParser = out.reduce<Record<string, number>>((a, s) => ((a[s.parser] = (a[s.parser] ?? 0) + 1), a), {});
console.log(`probed ${sources.length}; ${out.length} with upcoming dates (${out.reduce((a, b) => a + b.found, 0)} dates)`, byParser);
for (const s of out) console.log(String(s.found).padStart(4), s.parser.padEnd(6), s.provider_id);
if (!dry) {
  fs.writeFileSync(
    new URL('../src/data/course-date-sources.ts', import.meta.url),
    `// GENERATED by scripts/probe-course-dates.ts: providers whose published course\n// dates read cleanly (JSON-LD, iCal, Events Calendar REST or an HTML table with a\n// row config). Bundled into the build (a .json file next to the bundle wasn't\n// copied to dist).\nimport type { DateSource } from '../services/courseDates.js';\n\nexport const COURSE_DATE_SOURCES: DateSource[] = ${JSON.stringify(
      out.map(({ found, ...s }) => s),
      null,
      1,
    )};\n`,
  );
}
